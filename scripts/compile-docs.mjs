/**
 * Compiles the authored premise and specification docs into a module the
 * Worker can import.
 *
 * Workers have no filesystem, so the docs are inlined at build time — the same
 * pattern as compile-stories.mjs and compile-skills.mjs. The runtime reads
 * these through the `premise.read` capability rather than a hand-ported copy,
 * so the doc and the behaviour can only drift if the build is not re-run.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const DOCS = ['personality.md', 'spec.md', 'docs/DEVIATIONS.md'];
const OUTPUT = 'src/worker/docs/compiled.ts';

const entries = [];
for (const path of DOCS) {
  const body = await readFile(path, 'utf8');
  const title = path.replace(/^docs\//, '').replace(/\.md$/, '');
  entries.push({ id: title, title, body });
}

const body = `// Generated by scripts/compile-docs.mjs. Do not edit by hand.
//
// The authored premise and specification, inlined so the Worker can read them
// at runtime. The source of truth is the .md files these were built from.

export interface PremiseDoc {
  id: string;
  title: string;
  body: string;
}

export const PREMISE_DOCS: PremiseDoc[] = ${JSON.stringify(entries, null, 2)};
`;

await mkdir('src/worker/docs', { recursive: true });
await writeFile(OUTPUT, body, 'utf8');
console.log(`Wrote ${OUTPUT} (${entries.length} docs).`);
