/**
 * Compiles the bundled SKILL.md packages into a module the Worker imports.
 *
 * These ship with the deployment, so they land in the `global` tier and are
 * marked `bundled`. A user- or session-scoped package can never take one of
 * these names; the staging path rejects the collision rather than letting a
 * staged package shadow a trusted one.
 *
 * Bundling is not authorisation. A skill still declares which permissions it
 * needs, and the harness narrows those against what the session actually holds.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { join } from 'node:path';

const SOURCE_DIR = 'skills';
const OUTPUT = 'src/worker/skills/bundled.ts';

const entries = [];
let dirs = [];
try {
  dirs = (await readdir(SOURCE_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
} catch {
  console.log('  no skills directory; bundling nothing');
}

for (const dir of dirs) {
  const path = join(SOURCE_DIR, dir, 'SKILL.md');
  try {
    await stat(path);
  } catch {
    console.error(`\n${dir} has no SKILL.md\n`);
    process.exit(1);
  }

  const source = await readFile(path, 'utf8');
  const contentHash = createHash('sha256').update(source).digest('hex');

  // Supporting resources load after activation, so they are carried alongside
  // the instructions rather than inlined into them.
  const resources = {};
  for (const file of await readdir(join(SOURCE_DIR, dir))) {
    if (file === 'SKILL.md') continue;
    const resourcePath = join(SOURCE_DIR, dir, file);
    if ((await stat(resourcePath)).isFile()) {
      resources[file] = await readFile(resourcePath, 'utf8');
    }
  }

  entries.push({
    qualifiedName: dir,
    revision: contentHash.slice(0, 16),
    origin: 'anascummis/bundled',
    source,
    resources,
  });
  console.log(`  ${dir}@${contentHash.slice(0, 16)}`);
}

const body = `// Generated by scripts/compile-skills.mjs. Do not edit by hand.
//
// Skill packages that ship with the deployment. They are seeded into the
// global tier on first use, which is what makes their names reserved against
// user- and session-scoped packages.

export interface BundledSkill {
  qualifiedName: string;
  revision: string;
  origin: string;
  source: string;
  resources: Record<string, string>;
}

export const BUNDLED_SKILLS: BundledSkill[] = ${JSON.stringify(entries, null, 2)};
`;

await mkdir('src/worker/skills', { recursive: true });
await writeFile(OUTPUT, body, 'utf8');
console.log(`\nWrote ${OUTPUT} (${entries.length} skills).`);
