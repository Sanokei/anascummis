/**
 * Compiles the authored .ink sources into a module the Worker can import.
 *
 * Stories are immutable and versioned: the version is the content hash of the
 * source, so editing a story produces a new version rather than mutating one
 * that saved states were taken against. A checkpoint therefore either matches
 * a version exactly or is reported as incompatible.
 */
import { Compiler } from 'inkjs/full';
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, basename } from 'node:path';

const SOURCE_DIR = 'stories';
const OUTPUT = 'src/worker/stories/compiled.ts';

/** Which knot the host enters each story at. */
const ENTRY_KNOTS = {
  'open-conversation': 'listening',
  research: 'start',
  'build-capability': 'propose',
  'reply-surface': 'render',
  'show-and-tell': 'start',
};

const files = (await readdir(SOURCE_DIR)).filter((f) => f.endsWith('.ink')).sort();
const entries = [];

for (const file of files) {
  const id = basename(file, '.ink');
  const source = await readFile(join(SOURCE_DIR, file), 'utf8');

  let compiled;
  try {
    compiled = new Compiler(source).Compile().ToJson();
  } catch (err) {
    console.error(`\n${file} failed to compile:\n  ${err?.message ?? err}\n`);
    process.exit(1);
  }

  const version = createHash('sha256').update(source).digest('hex').slice(0, 16);
  const externals = [...new Set([...compiled.matchAll(/"x\(\)":"([^"]+)"/g)].map((m) => m[1]))];
  const entryKnot = ENTRY_KNOTS[id];
  if (!entryKnot) {
    console.error(`\n${file} has no declared entry knot in scripts/compile-stories.mjs\n`);
    process.exit(1);
  }

  entries.push({ id, version, entryKnot, compiled, externals });
  console.log(`  ${id}@${version}  ${externals.length} external${externals.length === 1 ? '' : 's'}`);
}

const body = `// Generated by scripts/compile-stories.mjs. Do not edit by hand.
//
// Compiled Ink artifacts, immutable per version. The version is the content
// hash of the source, so a saved runtime state either matches a story version
// exactly or is reported as incompatible rather than loaded anyway.

export interface CompiledStory {
  id: string;
  version: string;
  entryKnot: string;
  compiled: string;
  /** External function names found in compiler output, not in the source text. */
  externals: string[];
}

export const COMPILED_STORIES: CompiledStory[] = ${JSON.stringify(entries, null, 2)};
`;

await mkdir('src/worker/stories', { recursive: true });
await writeFile(OUTPUT, body, 'utf8');
console.log(`\nWrote ${OUTPUT} (${entries.length} stories).`);
